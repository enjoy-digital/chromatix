unsigned font_row(char c, int row)
{
	for (unsigned i = 0; i < sizeof(glyphs)/sizeof(glyphs[0]); i++)
		if (glyphs[i].c == c)
			return glyphs[i].rows[row];
	return 0;
}

int font_width(const char *text, int scale)
{
	int n = 0;

	while (text[n])
		n++;
	return n ? (n*(FONT_W + 1) - 1)*scale : 0;
}

/* Draws the row of a text line (row: 0 - FONT_H*scale - 1) at x, color per character (cycling over
   colors until a 0 entry). */
void font_text(uint8_t *line, int x, int row, const char *text, int scale, const uint8_t *colors)
{
	int ci = 0;

	if (row < 0 || row >= FONT_H*scale)
		return;
	for (; *text; text++, x += (FONT_W + 1)*scale) {
		unsigned bits = font_row(*text, row/scale);
		if (!colors[ci])
			ci = 0;
		for (int i = 0; i < FONT_W*scale; i++) {
			int px = x + i;
			if (px >= 0 && px < VR_WIDTH && (bits >> (FONT_W - 1 - i/scale)) & 1)
				line[px] = colors[ci];
		}
		if (*text != ' ')
			ci++;
	}
}
